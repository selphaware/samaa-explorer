def preflight_environment() -> None:
    if sys.version_info < (3, 10):
        raise HarnessError(f"Python >= 3.10 required, running {sys.version.split()[0]} at {sys.executable}")
    try:
        import playwright.sync_api  # noqa: F401
    except Exception as e:
        raise HarnessError(
            f"playwright is not importable from {sys.executable} ({e.__class__.__name__}: {e}). "
            f"The gate must run under the project venv interpreter.")


def preflight_network() -> None:
    for name, url in PREFLIGHT_URLS:
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": UA}), timeout=25) as r:
                if r.status != 200:
                    raise HarnessError(f"{name} answered HTTP {r.status} to a known-good probe - service outage, retry later")
                r.read(64)
        except HarnessError:
            raise
        except Exception as e:
            raise HarnessError(
                f"{name} is unreachable from this machine ({e.__class__.__name__}: {e}). "
                f"Network / DNS / proxy problem - not a deliverable problem.")


