NUMBER_JUNK_RE = re.compile(r"[,\s   ']")


def cell_number(s) -> float | None:
    """Parse a rendered numeric cell. Thousands separators (',', thin / no-break spaces, '),
    a typographic minus and a leading '+' are allowed; anything else is not a number."""
    t = NUMBER_JUNK_RE.sub("", str(s)).replace("−", "-").replace("–", "-")
    if not re.fullmatch(r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?", t):
        return None
    return float(t)


def column_values(headers: list[str], rows: list[list[str]], header_re: re.Pattern):
    """(index, raw cells, parsed numbers) of the first column whose header matches header_re."""
    idx = next((i for i, h in enumerate(headers) if header_re.search(h)), None)
    if idx is None:
        return None, [], []
    raw = [c[idx] if idx < len(c) else "" for c in rows]
    return idx, raw, [cell_number(v) for v in raw]


def ang_sep_deg(ra1, dec1, ra2, dec2) -> float:
    r = math.radians
    a = math.sin(r(dec1)) * math.sin(r(dec2)) + math.cos(r(dec1)) * math.cos(r(dec2)) * math.cos(r(ra1 - ra2))
    return math.degrees(math.acos(max(-1.0, min(1.0, a))))


