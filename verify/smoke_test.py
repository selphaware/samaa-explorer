def check_error_surfacing(page, net: NetLog, rep: Report, base_url: str, kind: str) -> None:
    """Reload, make one upstream service fail, click Explore, require an honest error message."""
    if kind == "catalogue":
        pattern = re.compile(r"simbad\.cds\.unistra\.fr")
        status = 503
    else:
        pattern = re.compile(r"alasky(bis)?\.cds\.unistra\.fr/hips-image-services")
        status = 500

    def handler(route):
        route.fulfill(status=status, content_type="text/plain",
                      headers={"Access-Control-Allow-Origin": "*"}, body=f"gate-injected {status}")

    page.route(pattern, handler)
    try:
        page.goto(base_url, wait_until="load")
        if not select_preset(page, Report()):
            rep.fail(f"[{kind} failure test] could not re-select the preset after reload")
            return
        explore = find_explore(page, Report())
        if explore is None:
            rep.fail(f"[{kind} failure test] Explore button missing after reload")
            return
        explore.click()
        deadline = time.time() + 8  # the injected failure answers instantly; 8 s is generous
        texts: list[str] = []
        body = ""
        while time.time() < deadline:
            texts = page.evaluate(JS_ALERT_TEXTS)
            body = page.evaluate(JS_BODY_TEXT)
            if kind == "catalogue":
                if any(re.search(r"\b503\b", t) for t in texts):
                    break
            else:
                if any(re.search(r"hips2fits|image|cutout", t, re.I) and re.search(r"\b500\b|error|fail|unavailable|could not|couldn't|cannot|unable", t, re.I) for t in texts):
                    break
            page.wait_for_timeout(250)
        if kind == "catalogue":
            hit = next((t for t in texts if re.search(r"\b503\b", t)), None)
            rep.check(hit is not None and re.search(r"simbad|catalog", hit, re.I) is not None,
                      f"SIMBAD 503 surfaced as an error naming service and status: {hit!r}",
                      f"after SIMBAD answered 503 no alert text named the status code and the service "
                      f"(contract: e.g. 'Catalogue error: SIMBAD TAP returned HTTP 503'); alerts: {texts[:4]}")
            rep.check(not re.search(r"no (catalogued |catalogued-)?objects", body, re.I),
                      "a dead catalogue is not presented as an empty sky",
                      "page shows 'No catalogued objects...' after a 503 - an upstream error must never render as the empty state")
        else:
            hit = next((t for t in texts if re.search(r"hips2fits|image|cutout", t, re.I) and
                        re.search(r"\b500\b|error|fail|unavailable|could not|couldn't|cannot|unable", t, re.I)), None)
            rep.check(hit is not None,
                      f"hips2fits 500 surfaced as an error naming the image service: {hit!r}",
                      f"after hips2fits answered 500 no alert text reported an image/hips2fits error "
                      f"(contract: <img>.onerror must render a message in a role=\"alert\" element); alerts: {texts[:4]}")
    finally:
        page.unroute(pattern, handler)


def run_gate(index: Path, port: int, timeout: float, min_rows: int, label: str, headed: bool = False) -> int:
    rep = Report()
    ARTIFACTS.mkdir(parents=True, exist_ok=True)
    rep.info(f"gate {label}: {index}  (python {sys.version.split()[0]} at {sys.executable})")
    app_dir = index.parent
    if not app_dir.is_dir():
        raise UsageError(f"directory does not exist: {app_dir}")
    if not index.is_file():
        rep.fail(f"deliverable entry point missing: {index}")
    for rel in REQUIRED_FILES:
        p = app_dir / rel
        if not p.is_file():
            rep.fail(f"missing deliverable file: {app_dir.name}/{rel}")
        elif p.stat().st_size == 0:
            rep.fail(f"empty deliverable file: {app_dir.name}/{rel}")
    if rep.fails:
        return finish(rep, label)
    rep.ok(f"all {len(REQUIRED_FILES)} deliverable files present and non-empty under {app_dir}")

    preflight_environment()
    preflight_network()
    from playwright.sync_api import sync_playwright

    nonce = f"{os.getpid()}-{int(time.time() * 1000)}"
    srv, port = start_server(app_dir, port, rep, nonce)
    base_url = f"http://localhost:{port}/{index.name}"
    page = None
    try:
        with sync_playwright() as pw:
            try:
                browser = pw.chromium.launch(headless=not headed)
            except Exception as e:
                raise HarnessError(f"Chromium failed to launch: {e}. Run: \"{sys.executable}\" -m playwright install chromium")
            ctx = browser.new_context(viewport={"width": 1280, "height": 900})
            page = ctx.new_page()
            page.set_default_timeout(10000)
            net = NetLog(page)
            try:
                resp = page.goto(base_url, wait_until="load")
            except Exception as e:
                if "ERR_CONNECTION_REFUSED" in str(e):
                    base_url = base_url.replace("localhost", "127.0.0.1")
                    rep.info("localhost refused (IPv6?); using 127.0.0.1")
                    resp = page.goto(base_url, wait_until="load")
                else:
                    raise
            served_by = (resp.headers.get("x-samaa-gate") if resp is not None else None)
            if served_by != nonce:
                raise HarnessError(
                    f"{base_url} was answered by a different server (expected nonce {nonce}, got {served_by!r}). "
                    f"Another gate run or dev server is on port {port}; stop it or pass --port.")
            rep.check(resp is not None and resp.status == 200, f"page served: {base_url} (by this gate's server)",
                      f"page did not load: HTTP {resp.status if resp else '?'} for {base_url}")
            page.wait_for_timeout(300)
            if net.page_errors:
                rep.fail("uncaught exception while loading the page: " + " | ".join(e[:200] for e in net.page_errors[:3]))
            if not select_preset(page, rep):
                return finish(rep, label, page)
            explore = find_explore(page, rep)
            if explore is None:
                return finish(rep, label, page)
            clicked_at = time.time()
            explore.click()
            outcome = wait_for_outcome(page, net, min_rows, timeout, clicked_at)
            rep.info(f"happy path settled: {outcome} after {time.time() - clicked_at:.1f}s "
                     f"({len(net.of_kind('image', clicked_at))} image, {len(net.of_kind('catalogue', clicked_at))} catalogue request(s))")
            rep.info(f"upstream timings: {net.timings(clicked_at)}")
            # Pull catalogue bodies now, before any navigation evicts them.
            for r in net.of_kind("catalogue", clicked_at):
                r["body"] = catalogue_body_text(r)
            try:
                page.screenshot(path=str(ARTIFACTS / f"gate_{label}.png"), full_page=True)
            except Exception as e:
                rep.info(f"screenshot failed: {e}")
            check_image(page, net, rep, clicked_at)
            check_catalogue(page, net, rep, clicked_at, min_rows)
            check_text(page, rep)
            check_console(net, rep)
            check_validation(page, net, rep, explore)
            net.collect_console = False  # injected failures legitimately log console errors
            check_error_surfacing(page, net, rep, base_url, "catalogue")
            check_error_surfacing(page, net, rep, base_url, "image")
            dump_requests(net, label)
            return finish(rep, label, page)
    finally:
        srv.shutdown()
        srv.server_close()


def dump_requests(net: NetLog, label: str) -> None:
    try:
        rows = [{k: v for k, v in r.items() if k not in ("response", "body")} for r in net.records if r["kind"]]
        (ARTIFACTS / f"gate_{label}_requests.json").write_text(json.dumps(rows, indent=1, default=str), encoding="utf-8")
    except Exception:
        pass


def finish(rep: Report, label: str, page=None) -> int:
    if rep.fails and page is not None:
        try:
            page.screenshot(path=str(ARTIFACTS / f"gate_{label}_fail.png"), full_page=True)
        except Exception:
            pass
    print()
    if rep.fails:
        print(f"GATE FAIL - {len(rep.fails)} of {len(rep.fails) + rep.passes} checks failed:")
        for f in rep.fails:
            print(f"  - {f}")
        print(f"(screenshots and request log in {ARTIFACTS})")
        code = EXIT_FAIL
    else:
        print(f"GATE PASS - {rep.passes} checks passed")
        code = EXIT_PASS
    try:
        (ARTIFACTS / f"gate_{label}_report.txt").write_text("\n".join(rep.lines), encoding="utf-8")
    except Exception:
        pass
    return code


