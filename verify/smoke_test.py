def selftest(port: int) -> int:
    print(f"SELFTEST using {sys.executable}")
    preflight_environment()
    preflight_network()
    tmp = Path(tempfile.mkdtemp(prefix="samaa-gate-selftest-"))
    proj = ARTIFACTS / "selftest"
    if proj.exists():
        shutil.rmtree(proj, ignore_errors=True)
    results: dict[str, dict[str, int]] = {"good": {}, "broken": {}}
    outputs: dict[str, str] = {}
    problems: list[str] = []

    def run(index: Path, label: str, *extra: str) -> tuple[int, str, float]:
        cmd = [sys.executable, str(HERE / "smoke_test.py"), str(index), "--port", str(port), "--label", label, *extra]
        t0 = time.time()
        p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=400)
        out = (p.stdout or "") + (p.stderr or "")
        outputs[label] = out
        return p.returncode, out, time.time() - t0

    try:
        for where, root in (("tempdir", tmp), ("projectdir", proj)):
            for kind, good in (("good", True), ("broken", False)):
                index = write_fixture(root / kind, kind)
                code, out, dt = run(index, f"selftest_{kind}_{where}", "--timeout", "45")
                results[kind][where] = code
                print(f"  {kind:6s} fixture from {where:10s}: exit {code} in {dt:.0f}s")
                if good and code != EXIT_PASS:
                    problems.append(f"GOOD fixture from {where} did not pass (exit {code}):\n{tail(out)}")
                if not good and code != EXIT_FAIL:
                    problems.append(f"BROKEN fixture from {where} did not FAIL with exit {EXIT_FAIL} (exit {code}):\n{tail(out)}")
                if not good and code == EXIT_FAIL:
                    for must in ("SWAPPED", "format=", "found in the live SIMBAD response",
                                 "not sorted descending", "select#sort", "field-census", "GROUP BY",
                                 "RA=400 was sent upstream", "503"):
                        if must not in out:
                            problems.append(f"BROKEN fixture from {where}: expected the gate output to mention {must!r}")
        # A CDS service failing the page mid-run must be a HARNESS ERROR (exit 3) that names the service - never
        # a GATE FAIL charged to the deliverable. The good fixture is run with each failure injected.
        good_index = write_fixture(tmp / "good", "good")
        for kind, mode, words in INJECT_CASES:
            label = f"selftest_inject_{kind}_{mode}"
            code, out, dt = run(good_index, label, "--timeout", "30", "--selftest-inject", f"{kind}:{mode}")
            print(f"  good fixture, {kind} {mode:9s} injected: exit {code} in {dt:.0f}s (expect {EXIT_HARNESS})")
            line = next((ln for ln in out.splitlines() if ln.startswith("HARNESS ERROR")), "")
            if code != EXIT_HARNESS or not line:
                problems.append(f"{kind} {mode} injected: expected HARNESS ERROR exit {EXIT_HARNESS}, got exit {code}:\n{tail(out)}")
                continue
            for w in words:
                if w not in line:
                    problems.append(f"{kind} {mode} injected: HARNESS ERROR line should mention {w!r}: {line[:300]}")
            if "GATE FAIL" in out:
                problems.append(f"{kind} {mode} injected: the gate must not also print GATE FAIL:\n{tail(out)}")
        # The converse: a request that provokes a REAL 500 from a healthy service (hips2fits width=0, SIMBAD 1/0)
        # is the deliverable's problem - exit 1 with the diagnosis, never HARNESS ERROR.
        index = write_fixture(tmp / "badreq", "badreq")
        code, out, dt = run(index, "selftest_badreq_tempdir", "--timeout", "45")
        print(f"  badreq fixture from tempdir   : exit {code} in {dt:.0f}s (expect {EXIT_FAIL})")
        if code != EXIT_FAIL:
            problems.append(f"BADREQ fixture (real 500s provoked by the request) must FAIL with exit {EXIT_FAIL}, got {code}:\n{tail(out)}")
        else:
            for must in ("upstream diagnosis", "is up", "request itself provokes the failure", "HTTP 500"):
                if must not in out:
                    problems.append(f"BADREQ fixture: expected the gate output to mention {must!r}:\n{tail(out)}")
            if "HARNESS ERROR" in out:
                problems.append(f"BADREQ fixture: a request-provoked 500 must not be reported as HARNESS ERROR:\n{tail(out)}")
        # Usage path: nonexistent directory.
        p = subprocess.run([sys.executable, str(HERE / "smoke_test.py"), str(tmp / "nope" / "index.html")],
                           capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=60)
        print(f"  nonexistent path: exit {p.returncode} (expect {EXIT_USAGE})")
        if p.returncode != EXIT_USAGE:
            problems.append(f"nonexistent path should exit {EXIT_USAGE}, got {p.returncode}")
        for kind in ("good", "broken"):
            vals = set(results[kind].values())
            if len(vals) > 1:
                problems.append(f"{kind} fixture verdict differs between tempdir and projectdir: {results[kind]}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
        shutil.rmtree(proj, ignore_errors=True)
    print()
    if problems:
        print("SELFTEST FAIL:")
        for pr in problems:
            print("  - " + pr.replace("\n", "\n    "))
        return EXIT_FAIL
    print(f"SELFTEST PASS - gate discriminates good from broken (results: {results})")
    return EXIT_PASS


def tail(s: str, n: int = 2500) -> str:
    return s if len(s) <= n else "...\n" + s[-n:]


