def check_preset_data(app_dir: Path, rep: Report, timeout: float) -> dict | None:
    """Static validation of data/presets.json, then five live re-resolutions through SIMBAD TAP.
    Returns the parsed document (None when it could not be parsed) for the select-structure check."""
    name = f"{app_dir.name}/{PRESETS_FILE}"
    path = app_dir / PRESETS_FILE
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except Exception as e:
        rep.fail(f"{name} is not valid JSON ({e.__class__.__name__}: {str(e)[:120]}) - it is generated by tools/build_presets.py, "
                 f"never written by hand")
        return None
    if not isinstance(doc, dict) or not isinstance(doc.get("presets"), list):
        rep.fail(f"{name} must be an object with a 'presets' array (got {type(doc).__name__}"
                 f"{' with keys ' + str(list(doc)[:6]) if isinstance(doc, dict) else ''})")
        return None
    presets = doc["presets"]
    rep.check(len(presets) >= MIN_PRESETS,
              f"{name} has {len(presets)} presets (need >= {MIN_PRESETS}); source={str(doc.get('source'))[:70]!r}",
              f"{name} has {len(presets)} presets (need >= {MIN_PRESETS}) - the library is tools/preset_catalogue.csv resolved by "
              f"tools/build_presets.py, not a demo list")
    problems: list[str] = []
    ids: dict[str, int] = {}
    good: list[dict] = []
    for i, p in enumerate(presets):
        tag = f"presets[{i}]" + (f" ({p.get('id')!r})" if isinstance(p, dict) and p.get("id") else "")
        before = len(problems)
        if not isinstance(p, dict):
            problems.append(f"{tag}: not an object")
            continue
        missing = [k for k in PRESET_REQUIRED_FIELDS if k not in p]
        if missing:
            problems.append(f"{tag}: missing field(s) {missing}")
            continue
        pid = p["id"]
        if not isinstance(pid, str) or not PRESET_ID_RE.match(pid):
            problems.append(f"{tag}: id {pid!r} is not a slug (lowercase letters, digits, hyphens)")
        elif pid in ids:
            problems.append(f"{tag}: duplicate id {pid!r} (also presets[{ids[pid]}])")
        else:
            ids[pid] = i
        for k in ("label", "main_id", "resolved_by"):
            if not isinstance(p[k], str) or not p[k].strip():
                problems.append(f"{tag}: {k} must be a non-empty string (got {p[k]!r})")
        if p["category"] not in PRESET_CATEGORIES:
            problems.append(f"{tag}: category {p['category']!r} is not one of {list(PRESET_CATEGORIES)}")
        for k, lo, hi, closed in (("ra", 0, 360, False), ("dec", -90, 90, True), ("fov", *PRESET_FOV_RANGE, True)):
            v = p[k]
            ok = isinstance(v, (int, float)) and not isinstance(v, bool) and math.isfinite(v) and lo <= v and (v <= hi if closed else v < hi)
            if not ok:
                problems.append(f"{tag}: {k} {v!r} must be a number in {'[' if True else ''}{lo}, {hi}{']' if closed else ')'}")
        for k in ("otype", "otype_desc"):
            if p[k] is not None and not isinstance(p[k], str):
                problems.append(f"{tag}: {k} must be a string or null")
        if not isinstance(p["resolved_at"], str) or not PRESET_DATE_RE.match(p["resolved_at"]):
            problems.append(f"{tag}: resolved_at {p['resolved_at']!r} must be YYYY-MM-DD")
        if len(problems) == before:
            good.append(p)
    rep.check(not problems,
              f"every preset carries {', '.join(PRESET_REQUIRED_FIELDS)}; ids unique, categories from the fixed set, ra/dec/fov in range",
              f"{len(problems)} invalid preset entr{'y' if len(problems) == 1 else 'ies'} in {name}:\n        "
              + "\n        ".join(problems[:8]) + ("\n        ..." if len(problems) > 8 else ""))
    rep.info("library by category: " + ", ".join(f"{c} {sum(1 for p in good if p['category'] == c)}" for c in PRESET_CATEGORIES))
    close: list[str] = []
    closest = (float("inf"), "?", "?")
    for i in range(len(good)):
        a = good[i]
        for j in range(i + 1, len(good)):
            b = good[j]
            sep = ang_sep_deg(a["ra"], a["dec"], b["ra"], b["dec"])
            if sep < closest[0]:
                closest = (sep, a["id"], b["id"])
            if sep < PRESET_MIN_SEPARATION_DEG:
                close.append(f"{a['id']} ({a['main_id']}) and {b['id']} ({b['main_id']}) are {sep * 3600:.1f} arcsec apart")
    rep.check(not close,
              f"no two presets within {PRESET_MIN_SEPARATION_DEG} deg (closest pair {closest[1]} / {closest[2]}: {closest[0]:.4f} deg)",
              f"presets on the same spot (limit {PRESET_MIN_SEPARATION_DEG} deg):\n        " + "\n        ".join(close[:6]))
    anchor = next((p for p in good if p["id"] == PRESET["id"]), None)
    rep.check(anchor is not None and ang_sep_deg(anchor["ra"], anchor["dec"], PRESET["ra"], PRESET["dec"]) <= COORD_TOL_DEG
              and re.search(PRESET["option_regex"], anchor["label"], re.I) is not None,
              f"anchor preset {PRESET['id']!r} is {anchor['label'] if anchor else '?'!r} at ({anchor['ra'] if anchor else '?'}, "
              f"{anchor['dec'] if anchor else '?'})",
              f"the library must contain id {PRESET['id']!r} labelled {PRESET['label']!r} at ({PRESET['ra']}, {PRESET['dec']}) - found {anchor!r}")
    if is_fixture_library(doc):
        rep.info(f"{name} is selftest fixture data (source={doc.get('source')!r}): live spot check skipped")
        return doc
    if len(ids) < PRESET_SPOT_COUNT:
        return doc
    # Five entries, chosen deterministically, must still be where SIMBAD says they are.
    picks = random.Random(PRESET_SPOT_SEED).sample(sorted(ids), PRESET_SPOT_COUNT)
    by_id = {p["id"]: p for p in good}
    outcomes: list[str | None] = []
    for pid in picks:
        p = by_id.get(pid)
        if p is None:
            continue
        adql = ("SELECT i.id, b.main_id, b.ra, b.dec FROM ident i JOIN basic b ON b.oid = i.oidref "
                f"WHERE i.id = '{p['main_id'].replace(chr(39), chr(39) * 2)}'")
        url = "https://simbad.cds.unistra.fr/simbad/sim-tap/sync?" + urllib.parse.urlencode(
            {"REQUEST": "doQuery", "LANG": "ADQL", "FORMAT": "json", "QUERY": adql})
        t0 = time.time()
        probe = http_probe(target_url("catalogue", url), None, min(timeout, DIAG_TIMEOUT_S))
        rec = {"url": url, "post": None, "method": "GET", "t": t0, "t_end": time.time(), "failed": None, "status": probe["status"]}
        if probe["status"] is None:
            # Raises HarnessError (exit 3) unless SIMBAD is demonstrably up and this exact request is what fails.
            resolve_upstream("catalogue", rec, "net", probe["detail"], rep, timeout)
            outcomes.append(f"{pid}: SIMBAD did not answer the lookup of {p['main_id']!r} ({probe['detail']})")
            continue
        if probe["status"] >= 500 or probe["status"] in (408, 429):
            resolve_upstream("catalogue", rec, "status", f"HTTP {probe['status']}", rep, timeout)
            outcomes.append(f"{pid}: SIMBAD answered HTTP {probe['status']} to the lookup of {p['main_id']!r}")
            continue
        if probe["status"] != 200:
            m = re.search(r'QUERY_STATUS"\s+value="ERROR">([^<]*)<', probe["body"] or "")
            outcomes.append(f"{pid}: lookup of main_id {p['main_id']!r} answered HTTP {probe['status']}: "
                            f"{(m.group(1).strip() if m else (probe['body'] or '')[:120])!r}")
            continue
        try:
            rows = [r for r in (json.loads(probe["body"]).get("data") or []) if r[2] is not None and r[3] is not None]
        except Exception as e:
            rows = []
            outcomes.append(f"{pid}: SIMBAD's answer could not be parsed ({e.__class__.__name__})")
            continue
        if not rows:
            outcomes.append(f"{pid} ({p['label']}): SIMBAD no longer knows main_id {p['main_id']!r} - re-run tools/build_presets.py")
            continue
        ra, dec = float(rows[0][2]), float(rows[0][3])
        sep = ang_sep_deg(ra, dec, p["ra"], p["dec"])
        outcomes.append(None if sep <= PRESET_SPOT_TOL_DEG else
                        f"{pid} ({p['label']}): presets.json says ({p['ra']}, {p['dec']}) but SIMBAD says ({ra:.6f}, {dec:.6f}) for "
                        f"{p['main_id']!r} - {sep:.4f} deg apart (limit {PRESET_SPOT_TOL_DEG}); re-run tools/build_presets.py")
    bad = [o for o in outcomes if o]
    rep.check(not bad,
              f"live spot check: {len(outcomes)} presets ({', '.join(picks)}) re-resolved in SIMBAD within {PRESET_SPOT_TOL_DEG} deg",
              f"live spot check (seed {PRESET_SPOT_SEED}) failed for {len(bad)} of {len(outcomes)} presets:\n        " + "\n        ".join(bad))
    return doc


