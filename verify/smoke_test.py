def write_fixture(root: Path, good: bool) -> Path:
    app = root / "app"
    (app / "css").mkdir(parents=True, exist_ok=True)
    (app / "js" / "services").mkdir(parents=True, exist_ok=True)
    title = "Gate fixture GOOD" if good else "Gate fixture BROKEN"
    (app / "index.html").write_text(FIXTURE_INDEX.format(title=title), encoding="utf-8")
    (app / "css" / "styles.css").write_text(FIXTURE_CSS, encoding="utf-8")
    (app / "js" / "presets.js").write_text(FIXTURE_PRESETS, encoding="utf-8")
    (app / "js" / "services" / "hips2fits.js").write_text(FIXTURE_HIPS_GOOD if good else FIXTURE_HIPS_BROKEN, encoding="utf-8")
    (app / "js" / "services" / "simbad.js").write_text(FIXTURE_SIMBAD_GOOD if good else FIXTURE_SIMBAD_BROKEN, encoding="utf-8")
    (app / "js" / "main.js").write_text(FIXTURE_MAIN_GOOD if good else FIXTURE_MAIN_BROKEN, encoding="utf-8")
    return app / "index.html"


def selftest(port: int) -> int:
    print(f"SELFTEST using {sys.executable}")
    preflight_environment()
    preflight_network()
    tmp = Path(tempfile.mkdtemp(prefix="samaa-gate-selftest-"))
    proj = ARTIFACTS / "selftest"
    if proj.exists():
        shutil.rmtree(proj, ignore_errors=True)
    results: dict[str, dict[str, int]] = {"good": {}, "broken": {}}
    outputs: dict[str, str] = {}
    problems: list[str] = []
    try:
        for where, root in (("tempdir", tmp), ("projectdir", proj)):
            for kind, good in (("good", True), ("broken", False)):
                index = write_fixture(root / kind, good)
                label = f"selftest_{kind}_{where}"
                cmd = [sys.executable, str(HERE / "smoke_test.py"), str(index), "--port", str(port),
                       "--timeout", "45", "--label", label]
                t0 = time.time()
                p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=400)
                out = (p.stdout or "") + (p.stderr or "")
                outputs[label] = out
                results[kind][where] = p.returncode
                print(f"  {kind:6s} fixture from {where:10s}: exit {p.returncode} in {time.time() - t0:.0f}s")
                if good and p.returncode != EXIT_PASS:
                    problems.append(f"GOOD fixture from {where} did not pass (exit {p.returncode}):\n{tail(out)}")
                if not good and p.returncode != EXIT_FAIL:
                    problems.append(f"BROKEN fixture from {where} did not FAIL with exit {EXIT_FAIL} (exit {p.returncode}):\n{tail(out)}")
                if not good and p.returncode == EXIT_FAIL:
                    for must in ("SWAPPED", "format=", f"0 requests to {CATALOGUE_HOST}", "RA=400 was sent upstream", "503"):
                        if must not in out:
                            problems.append(f"BROKEN fixture from {where}: expected the gate output to mention {must!r}")
        # Usage path: nonexistent directory.
        p = subprocess.run([sys.executable, str(HERE / "smoke_test.py"), str(tmp / "nope" / "index.html")],
                           capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=60)
        print(f"  nonexistent path: exit {p.returncode} (expect {EXIT_USAGE})")
        if p.returncode != EXIT_USAGE:
            problems.append(f"nonexistent path should exit {EXIT_USAGE}, got {p.returncode}")
        for kind in ("good", "broken"):
            vals = set(results[kind].values())
            if len(vals) > 1:
                problems.append(f"{kind} fixture verdict differs between tempdir and projectdir: {results[kind]}")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
        shutil.rmtree(proj, ignore_errors=True)
    print()
    if problems:
        print("SELFTEST FAIL:")
        for pr in problems:
            print("  - " + pr.replace("\n", "\n    "))
        return EXIT_FAIL
    print(f"SELFTEST PASS - gate discriminates good from broken (results: {results})")
    return EXIT_PASS


def tail(s: str, n: int = 2500) -> str:
    return s if len(s) <= n else "...\n" + s[-n:]


