def _net_code(failed: str | None) -> str:
    m = re.search(r"net::(ERR_[A-Z0-9_]+)", failed or "")
    return m.group(1) if m else (failed or "")


def upstream_verdict(rec: dict, outcome: str, now: float) -> tuple[str, str] | None:
    """What went wrong with one live upstream request, if anything the service could be blamed for:
    ('status', 'HTTP 503'), ('orb', 'net::ERR_BLOCKED_BY_ORB'), ('net', 'net::ERR_CONNECTION_REFUSED'),
    ('page', 'net::ERR_FAILED'), ('abort', '30.1s'), ('pending', '45.0s'), or None (fine, or a 4xx that the
    request itself earned). 'orb': Chromium discards a non-image answer to an <img> (an error page, 5xx or
    otherwise) as ERR_BLOCKED_BY_ORB without reporting the status - that is the service's answer, not the page's."""
    dur = (rec["t_end"] or now) - rec["t"]
    if rec["failed"]:
        code = _net_code(rec["failed"])
        if code == "ERR_ABORTED":
            return ("abort", f"{dur:.1f}s") if dur >= PAGE_TIMEOUT_ABORT_S else None
        if code == "ERR_BLOCKED_BY_ORB":
            return ("orb", rec["failed"])
        if code.startswith(PAGE_SIDE_NET_ERRORS):
            return ("page", rec["failed"])
        return ("net", rec["failed"])
    if rec["status"] is None:
        return ("pending", f"{dur:.1f}s") if outcome == "timeout" and rec["t_end"] is None else None
    if rec["status"] >= 500 or rec["status"] in (408, 429):
        return ("status", f"HTTP {rec['status']}")
    return None


VERDICT_PRIORITY = {"status": 0, "orb": 0, "net": 0, "page": 1, "abort": 2, "pending": 2}


def diagnose_upstream(net: "NetLog", since: float, outcome: str, rep: Report, timeout: float, label: str) -> None:
    """Called once the happy path has settled, before any check runs. Raises HarnessError (exit 3) when a CDS
    service failed the page for reasons the gate can lay at the service's door; logs an INFO line and returns
    when the service is demonstrably up and the page's own request is what fails."""
    now = time.time()
    cands = []
    for kind in ("image", "catalogue"):
        for r in net.of_kind(kind, since):
            if r.get("injected"):
                continue
            v = upstream_verdict(r, outcome, now)
            if v:
                cands.append((VERDICT_PRIORITY[v[0]], r["t"], kind, r, v))
    if not cands:
        return
    cands.sort(key=lambda c: (c[0], c[1]))
    seen: set[str] = set()
    for _, _, kind, r, (what, detail) in cands:
        if kind in seen:
            continue
        seen.add(kind)
        try:
            resolve_upstream(kind, r, what, detail, rep, timeout)
        except HarnessError:
            dump_requests(net, label)
            write_report(rep, label)
            raise


def resolve_upstream(kind: str, r: dict, what: str, detail: str, rep: Report, timeout: float) -> None:
    svc = SERVICE_LABEL[kind]
    dur = (r["t_end"] or time.time()) - r["t"]
    happened = {
        "status": f"was answered {detail} after {dur:.1f}s",
        "orb": f"got a non-image answer (an error page) that the browser discarded as {detail} after {dur:.1f}s",
        "net": f"failed at network level ({detail}) after {dur:.1f}s",
        "page": f"failed in the browser ({detail}) after {dur:.1f}s",
        "abort": f"was aborted by the page after {detail} (its own request timeout)",
        "pending": f"was still unanswered after {detail}",
    }[what]
    head = f"{svc}: the page's {kind} request {happened}"
    advice = "Upstream problem, not the deliverable: wait a minute, re-run the gate, and do not change app/."
    diag_t = min(timeout, DIAG_TIMEOUT_S)
    rep.info(f"upstream diagnosis: {head}; probing {svc} with the gate's own known-good request ...")
    probe = http_probe(target_url(kind, diag_probe_url(kind)), None, diag_t)
    probe_ok = probe["status"] is not None and 200 <= probe["status"] < 300
    if probe["status"] is not None:
        probe_txt = f"the gate's own known-good {kind} request was answered HTTP {probe['status']} in {probe['seconds']:.1f}s"
    else:
        probe_txt = f"the gate's own known-good {kind} request failed too ({probe['detail']} after {probe['seconds']:.1f}s)"
    if not probe_ok:
        raise HarnessError(f"{head}, and {probe_txt}. {advice}")
    if what == "net":
        raise HarnessError(f"{head}; {probe_txt}, so the failure was transient. {advice}")
    if what in ("abort", "pending") and probe["seconds"] > SLOW_PROBE_S:
        raise HarnessError(f"{head}; {probe_txt} (normally about 1 s): an upstream slow spell. {advice}")
    # The service answers the gate normally. Replay the page's exact request (twice if it fails) to tell a
    # transient or flapping failure from a request that provokes the error every time.
    replay = None
    for attempt in (1, 2):
        t_replay = time.time()
        replay = http_probe(target_url(kind, r["url"]), r["post"], diag_t)
        gap = t_replay - (r["t_end"] or t_replay)
        ok = replay["status"] is not None and 200 <= replay["status"] < 300
        if replay["status"] is None:
            if what in ("abort", "pending") and replay["detail"] == "timed out":
                rep.info(f"upstream diagnosis: {svc} is up ({probe_txt}), yet the page's {kind} request {happened} and "
                         f"the gate's replay of that exact request also timed out after {replay['seconds']:.1f}s. The "
                         f"request itself is too slow for the service (a full scan - DISTANCE in WHERE instead of "
                         f"CONTAINS, a join without the cone, no TOP?), so the FAIL lines below are the deliverable's. "
                         f"Request: {r['method']} {r['url'][:200]}")
                return
            raise HarnessError(f"{head}; {probe_txt}, but the gate's replay of the page's request failed "
                               f"({replay['detail']} after {replay['seconds']:.1f}s). {advice}")
        if ok:
            if what == "page" and not replay["acao"]:
                raise HarnessError(f"{head}; the gate's replay got HTTP {replay['status']} WITHOUT an "
                                   f"Access-Control-Allow-Origin header, so the browser could not use it: the service's "
                                   f"CORS is misconfigured right now. {advice}")
            if what == "page":
                rep.info(f"upstream diagnosis: {svc} is up ({probe_txt}) and the page's exact request replayed by the "
                         f"gate got HTTP {replay['status']} with Access-Control-Allow-Origin {replay['acao']!r}; the "
                         f"browser itself refused it ({detail}): a CORS-triggering header, credentials mode, CSP or an "
                         f"aborted request, all of which the deliverable controls. Request: {r['method']} {r['url'][:200]}")
                return
            raise HarnessError(f"{head}, but the gate replayed the same request {gap:.0f}s later (attempt {attempt}) "
                               f"and got HTTP {replay['status']} in {replay['seconds']:.1f}s ({probe_txt}): a transient "
                               f"upstream failure. {advice}")
        if attempt == 1:
            time.sleep(2)
    m = re.search(r'QUERY_STATUS"\s+value="ERROR">([^<]*)<', replay["body"] or "")
    says = (m.group(1).strip() if m else (replay["body"] or "").strip())[:160]
    rep.info(f"upstream diagnosis: {svc} is up ({probe_txt}), yet the page's {kind} request {happened} and the gate's "
             f"replay of that exact request got {replay['detail']} twice ({replay['seconds']:.1f}s)"
             f"{'; the service says: ' + repr(says) if says else ''}. The request itself provokes the failure, so the "
             f"FAIL lines below are the deliverable's. Request: {r['method']} {r['url'][:200]}")


class Injection:
    """--selftest-inject KIND:MODE (selftest only). The page sees KIND fail in MODE (503, 500, refuse, hang,
    transient) and, except for 'transient', the gate's own probes go to a local chaos server that fails the same
    way, so the selftest can prove that an upstream outage is a HARNESS ERROR (exit 3), never the deliverable's
    fault. It can only make a run exit 3 or 1, never pass."""
    MODES = ("503", "500", "refuse", "hang", "transient")

    def __init__(self, spec: str) -> None:
        kind, _, mode = spec.partition(":")
        if kind not in SERVICE_LABEL or mode not in self.MODES:
            raise UsageError(f"--selftest-inject expects <image|catalogue>:<{'|'.join(self.MODES)}>, got {spec!r}")
        self.kind, self.mode = kind, mode
        self.netloc: str | None = None
        self.server = None
        self.open_routes: list = []                  # 'hang' routes still waiting, released at teardown

    def start(self) -> None:
        if self.mode == "transient":
            return                                   # the gate's own requests go to the real, healthy service
        if self.mode == "refuse":
            s = socket.socket()
            s.bind(("127.0.0.1", 0))
            port = s.getsockname()[1]
            s.close()
            self.netloc = f"127.0.0.1:{port}"       # nothing listens there: connection refused
            return
        mode = self.mode

        class Chaos(BaseHTTPRequestHandler):
            def log_message(self, *a) -> None:
                pass

            def do_GET(self) -> None:
                self._answer()

            def do_POST(self) -> None:
                self._answer()

            def _answer(self) -> None:
                if mode == "hang":
                    time.sleep(600)
                    return
                body = b"chaos"
                self.send_response(int(mode))
                self.send_header("Content-Type", "text/plain")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                self.wfile.write(body)

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Chaos)
        threading.Thread(target=self.server.serve_forever, kwargs={"poll_interval": 0.2}, daemon=True).start()
        self.netloc = f"127.0.0.1:{self.server.server_address[1]}"

    def rewrite(self, kind: str, url: str) -> str:
        if kind != self.kind or not self.netloc:
            return url
        return urllib.parse.urlsplit(url)._replace(scheme="http", netloc=self.netloc).geturl()

    def route(self, page) -> None:
        mode = self.mode

        def handler(route):
            if mode == "hang":
                self.open_routes.append(route)       # never answered now: the request stays pending
                return
            if mode == "refuse":
                route.abort("connectionrefused")
                return
            status = 503 if mode in ("503", "transient") else int(mode)
            route.fulfill(status=status, content_type="text/plain", headers={"Access-Control-Allow-Origin": "*"},
                          body=f"selftest-injected {status}")

        page.route(HOST_PATTERNS[self.kind], handler)

    def release(self) -> None:
        """Answer every hung route (while the page is still open) so Playwright completes the handlers
        instead of cancelling them at teardown, which would print asyncio noise."""
        for route in self.open_routes:
            try:
                route.abort("timedout")
            except Exception:
                pass
        self.open_routes.clear()

    def stop(self) -> None:
        if self.server is not None:
            self.server.shutdown()
            self.server.server_close()


