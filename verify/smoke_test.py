def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("path", nargs="?", help="path to app/index.html")
    ap.add_argument("--port", type=int, default=int(os.environ.get("SAMAA_GATE_PORT", "8765")))
    ap.add_argument("--timeout", type=float, default=45.0, help="seconds to wait for image + table after Explore")
    ap.add_argument("--min-rows", type=int, default=MIN_ROWS_DEFAULT)
    ap.add_argument("--label", default="run", help="artifact file label")
    ap.add_argument("--headed", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    try:
        if a.selftest:
            return selftest(a.port)
        if not a.path:
            raise UsageError("missing argument: path to app/index.html (or --selftest)")
        index = Path(a.path).resolve()
        if index.is_dir():
            index = index / "index.html"
        return run_gate(index, a.port, a.timeout, a.min_rows, a.label, a.headed)
    except UsageError as e:
        print(f"USAGE ERROR - {e}", file=sys.stderr)
        return EXIT_USAGE
    except HarnessError as e:
        print(f"HARNESS ERROR - this is not a deliverable problem: {e}", file=sys.stderr)
        return EXIT_HARNESS
    except KeyboardInterrupt:
        print("HARNESS ERROR - interrupted", file=sys.stderr)
        return EXIT_HARNESS
    except Exception as e:  # anything unexpected inside the harness itself
        print("HARNESS ERROR - this is not a deliverable problem: the gate itself crashed:", file=sys.stderr)
        traceback.print_exc()
        return EXIT_HARNESS


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
