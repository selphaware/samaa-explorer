def _host(url: str) -> str:
    try:
        return (urllib.parse.urlsplit(url).hostname or "").lower()
    except Exception:
        return ""


def classify(url: str) -> str | None:
    h = _host(url)
    if h in IMAGE_HOSTS and IMAGE_PATH_HINT in url:
        return "image"
    if h == CATALOGUE_HOST:
        return "catalogue"
    return None


class NetLog:
    def __init__(self, page) -> None:
        self.records: list[dict] = []
        self.by_request: dict[object, dict] = {}
        self.console_errors: list[str] = []
        self.page_errors: list[str] = []
        self.pending = 0
        self.last_activity = time.time()
        self.collect_console = True
        page.on("request", self._on_request)
        page.on("response", self._on_response)
        page.on("requestfinished", self._on_done)
        page.on("requestfailed", self._on_failed)
        page.on("console", self._on_console)
        page.on("pageerror", self._on_pageerror)

    def _on_request(self, req) -> None:
        self.pending += 1
        self.last_activity = time.time()
        rec = {
            "url": req.url, "method": req.method, "post": req.post_data,
            "kind": classify(req.url), "status": None, "ctype": None, "failed": None,
            "response": None, "t": time.time(), "t_end": None,
        }
        self.records.append(rec)
        self.by_request[req] = rec

    def _on_response(self, resp) -> None:
        rec = self.by_request.get(resp.request)
        if rec is None:
            return
        rec["status"] = resp.status
        rec["ctype"] = (resp.headers.get("content-type") or "").lower()
        rec["response"] = resp

    def _on_done(self, req) -> None:
        self.pending = max(0, self.pending - 1)
        self.last_activity = time.time()
        rec = self.by_request.get(req)
        if rec is not None:
            rec["t_end"] = time.time()

    def _on_failed(self, req) -> None:
        self.pending = max(0, self.pending - 1)
        self.last_activity = time.time()
        rec = self.by_request.get(req)
        if rec is not None:
            rec["failed"] = (req.failure or "failed")
            rec["t_end"] = time.time()

    def timings(self, since: float) -> str:
        parts = []
        for r in self.records:
            if r["kind"] and r["t"] >= since:
                dur = (r["t_end"] or time.time()) - r["t"]
                parts.append(f"{r['kind']} HTTP {r['status']} in {dur:.1f}s")
        return ", ".join(parts) or "none"

    def _on_console(self, msg) -> None:
        if not self.collect_console or msg.type != "error":
            return
        text = msg.text or ""
        if re.search(r"favicon", text, re.I):
            return
        loc = ""
        try:
            if msg.location and msg.location.get("url"):
                loc = f" @ {msg.location['url']}:{msg.location.get('lineNumber', 0)}"
        except Exception:
            pass
        self.console_errors.append(text + loc)

    def _on_pageerror(self, err) -> None:
        if self.collect_console:
            self.page_errors.append(str(err))

    def of_kind(self, kind: str, since: float = 0.0) -> list[dict]:
        return [r for r in self.records if r["kind"] == kind and r["t"] >= since]


def request_params(rec: dict) -> dict[str, str]:
    """All query params (URL + form body), lower-cased keys, URL-decoded values."""
    out: dict[str, str] = {}
    q = urllib.parse.urlsplit(rec["url"]).query
    for k, v in urllib.parse.parse_qsl(q, keep_blank_values=True):
        out[k.lower()] = v
    post = rec.get("post") or ""
    if post and "=" in post:
        for k, v in urllib.parse.parse_qsl(post, keep_blank_values=True):
            out[k.lower()] = v
    return out


def to_float(s) -> float | None:
    try:
        return float(str(s).strip())
    except Exception:
        return None


def ang_sep_deg(ra1, dec1, ra2, dec2) -> float:
    r = math.radians
    a = math.sin(r(dec1)) * math.sin(r(dec2)) + math.cos(r(dec1)) * math.cos(r(dec2)) * math.cos(r(ra1 - ra2))
    return math.degrees(math.acos(max(-1.0, min(1.0, a))))


