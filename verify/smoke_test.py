def wait_for_outcome(page, net: NetLog, min_rows: int, timeout: float, clicked_at: float) -> str:
    """Poll until the happy-path criteria are met, the page goes quiet, or the deadline passes."""
    deadline = clicked_at + timeout
    while True:
        img_ok = cat_ok = rows_ok = False
        for r in net.of_kind("image", clicked_at):
            if r["status"] == 200 and (r["ctype"] or "").startswith("image/"):
                img_ok = True
        for r in net.of_kind("catalogue", clicked_at):
            if r["status"] is not None and 200 <= r["status"] < 300:
                cat_ok = True
        if img_ok:
            st = page.evaluate(JS_IMAGE_STATE)
            img_ok = bool(st.get("found") and st.get("complete") and st.get("naturalWidth", 0) >= MIN_NATURAL_WIDTH)
        if cat_ok:
            tb = page.evaluate(JS_TABLE_STATE)
            rows_ok = bool(tb.get("found") and len(tb.get("rows", [])) >= min_rows)
            body = page.evaluate(JS_BODY_TEXT)
            rows_ok = rows_ok and bool(re.search(r"showing\s+[\d,]+\s+of\s+[\d,]+", body, re.I))
        if img_ok and cat_ok and rows_ok:
            return "ready"
        now = time.time()
        if now > deadline:
            return "timeout"
        if now - clicked_at > 6 and net.pending == 0 and now - net.last_activity > 3:
            return "quiet"
        page.wait_for_timeout(250)


def check_image(page, net: NetLog, rep: Report, since: float) -> None:
    reqs = net.of_kind("image", since)
    if not rep.check(bool(reqs),
                     f"{len(reqs)} request(s) to hips2fits host(s) {IMAGE_HOSTS}",
                     f"0 requests to a hips2fits host {IMAGE_HOSTS} after clicking Explore - "
                     f"the image panel is not fetching a real cutout"):
        return
    good: dict | None = None
    problems: list[str] = []
    for r in reqs:
        p = request_params(r)
        issues = []
        ra, dec = to_float(p.get("ra")), to_float(p.get("dec"))
        if ra is None or dec is None:
            issues.append(f"ra/dec missing from query (ra={p.get('ra')!r}, dec={p.get('dec')!r})")
        else:
            if ang_sep_deg(ra, dec, PRESET["ra"], PRESET["dec"]) > COORD_TOL_DEG:
                swapped = (abs(ra - PRESET["dec"]) < COORD_TOL_DEG and abs(dec - PRESET["ra"]) < COORD_TOL_DEG)
                issues.append(
                    f"ra={ra}, dec={dec} but {PRESET['label']} is ra={PRESET['ra']}, dec={PRESET['dec']} "
                    f"(tolerance {COORD_TOL_DEG} deg)" + (" - RA AND DEC ARE SWAPPED" if swapped else " - wrong place"))
        fmt = (p.get("format") or "").lower()
        if fmt not in ("jpg", "jpeg", "png"):
            issues.append(f"format={p.get('format')!r} - must be jpg or png (service default is FITS, which <img> cannot render)")
        hips = p.get("hips") or ""
        if "/" not in hips:
            issues.append(f"hips={hips!r} - must be a full HiPS ID such as CDS/P/DSS2/color, never a keyword")
        fov = to_float(p.get("fov"))
        if fov is None or not (FOV_RANGE_DEG[0] <= fov <= FOV_RANGE_DEG[1]):
            issues.append(f"fov={p.get('fov')!r} - must be decimal DEGREES in [{FOV_RANGE_DEG[0]}, {FOV_RANGE_DEG[1]}] (arcminutes?)")
        w, h = to_float(p.get("width")), to_float(p.get("height"))
        if w is None or h is None or w < MIN_NATURAL_WIDTH or h < MIN_NATURAL_WIDTH:
            issues.append(f"width={p.get('width')!r} height={p.get('height')!r} - both required, >= {MIN_NATURAL_WIDTH} px")
        if r["failed"]:
            issues.append(f"request failed at network level: {r['failed']}")
        elif r["status"] != 200 or not (r["ctype"] or "").startswith("image/"):
            issues.append(f"response was HTTP {r['status']} content-type={r['ctype']!r} (need 200 image/*)")
        if not issues:
            good = r
        else:
            problems.append(f"{r['method']} {r['url'][:160]}... -> " + "; ".join(issues))
    if good is None:
        rep.fail("no hips2fits request satisfied the contract:\n        " + "\n        ".join(problems))
    else:
        p = request_params(good)
        rep.ok(f"hips2fits request OK: hips={p.get('hips')} ra={p.get('ra')} dec={p.get('dec')} fov={p.get('fov')} "
               f"{p.get('width')}x{p.get('height')} format={p.get('format')} -> HTTP {good['status']} {good['ctype']}")
    st = page.evaluate(JS_IMAGE_STATE)
    if not st.get("found"):
        rep.fail(f"no <img> showing the cutout found ({st.get('imgCount', 0)} <img> elements on page; "
                 f"contract: <img id=\"sky-image\">)")
        return
    src = st.get("src") or ""
    src_ok = True
    if re.match(r"^(blob|data):", src, re.I):
        src_desc = f"{src[:30]}... (fetched by script)"
    elif classify(src) == "image":
        p = request_params({"url": src, "post": None})
        ra, dec = to_float(p.get("ra")), to_float(p.get("dec"))
        src_ok = ra is not None and dec is not None and ang_sep_deg(ra, dec, PRESET["ra"], PRESET["dec"]) <= COORD_TOL_DEG
        src_desc = f"hips2fits ra={p.get('ra')} dec={p.get('dec')}"
    else:
        src_ok = False
        src_desc = src[:120] or "(empty)"
    rep.check(src_ok, f"<img{'#' + st['id'] if st.get('id') else ''}> src is the live cutout: {src_desc}",
              f"<img{'#' + st['id'] if st.get('id') else ''}> src is not the M31 cutout from hips2fits: {src_desc}")
    rep.check(bool(st.get("complete")) and st.get("naturalWidth", 0) >= MIN_NATURAL_WIDTH,
              f"image decoded: naturalWidth={st.get('naturalWidth')} naturalHeight={st.get('naturalHeight')}",
              f"image not decoded: complete={st.get('complete')} naturalWidth={st.get('naturalWidth')} "
              f"(need >= {MIN_NATURAL_WIDTH}) - broken <img>, wrong bytes (FITS?), or onerror swallowed")
    rep.check(bool(st.get("visible")) and st.get("width", 0) >= MIN_RENDERED_WIDTH,
              f"image visible on screen: {st.get('width'):.0f}x{st.get('height'):.0f} css px",
              f"image not visible or too small on screen: visible={st.get('visible')} width={st.get('width')} "
              f"(need >= {MIN_RENDERED_WIDTH} css px)")


def catalogue_body_text(rec: dict) -> str:
    resp = rec.get("response")
    if resp is None:
        return ""
    try:
        return resp.text()
    except Exception:
        return ""


def check_catalogue(page, net: NetLog, rep: Report, since: float, min_rows: int) -> None:
    reqs = net.of_kind("catalogue", since)
    if not rep.check(bool(reqs),
                     f"{len(reqs)} request(s) to {CATALOGUE_HOST}",
                     f"0 requests to {CATALOGUE_HOST} after clicking Explore - table is not backed by a live "
                     f"SIMBAD query (fixture data?)"):
        return
    queries: list[tuple[dict, str]] = []
    for r in reqs:
        p = request_params(r)
        q = p.get("query") or ""
        if not q:
            rep.fail(f"catalogue request has no ADQL QUERY parameter: {r['method']} {r['url'][:160]} - "
                     f"TAP sync expects REQUEST=doQuery&LANG=ADQL&FORMAT=json&QUERY=<ADQL>")
            continue
        queries.append((r, q))
    if not queries:
        return
    # Every ADQL query the page sends must carry TOP n, n <= MAX_TOP.
    bad_top = []
    for r, q in queries:
        m = TOP_RE.search(q)
        if not m:
            bad_top.append(f"no TOP cap: {q[:140]}")
        elif not (1 <= int(m.group(1)) <= MAX_TOP):
            bad_top.append(f"TOP {m.group(1)} exceeds {MAX_TOP}: {q[:140]}")
    rep.check(not bad_top, f"all {len(queries)} ADQL query(ies) carry TOP n with n <= {MAX_TOP}",
              "ADQL without a valid TOP cap:\n        " + "\n        ".join(bad_top))
    # At least one cone centred on the preset.
    cone_hits = []
    cone_misses = []
    for r, q in queries:
        m = CIRCLE_RE.search(q)
        if not m:
            cone_misses.append(f"no CIRCLE( in: {q[:140]}")
            continue
        ra, dec, rad = float(m.group(1)), float(m.group(2)), float(m.group(3))
        sep = ang_sep_deg(ra, dec, PRESET["ra"], PRESET["dec"])
        if sep > COORD_TOL_DEG:
            swapped = (abs(ra - PRESET["dec"]) < COORD_TOL_DEG and abs(dec - PRESET["ra"]) < COORD_TOL_DEG)
            cone_misses.append(f"CIRCLE centre ({ra}, {dec}) is {sep:.3f} deg from {PRESET['label']}"
                               + (" - RA AND DEC ARE SWAPPED" if swapped else ""))
        elif not (RADIUS_RANGE_DEG[0] <= rad <= RADIUS_RANGE_DEG[1]):
            cone_misses.append(f"CIRCLE radius {rad} deg outside {RADIUS_RANGE_DEG} (arcminutes? FoV instead of FoV/2?)")
        else:
            cone_hits.append((r, q, rad))
    rep.check(bool(cone_hits),
              f"ADQL cone centred on {PRESET['label']} within {COORD_TOL_DEG} deg, radius {cone_hits[0][2] if cone_hits else '?'} deg",
              "no ADQL query contains CIRCLE( centred on the selected preset:\n        " + "\n        ".join(cone_misses))
    # Responses must be non-error.
    errors = []
    bodies = []
    for r, q in queries:
        if r["failed"]:
            errors.append(f"network failure ({r['failed']}): {q[:100]}")
        elif r["status"] is None:
            errors.append(f"no response received: {q[:100]}")
        elif not (200 <= r["status"] < 300):
            body = catalogue_body_text(r)
            msg = re.search(r'QUERY_STATUS"\s+value="ERROR">([^<]*)<', body)
            errors.append(f"HTTP {r['status']} {r['ctype']}: {msg.group(1).strip() if msg else body[:160]!r} for {q[:100]}")
        else:
            bodies.append(catalogue_body_text(r))
    rep.check(not errors, f"all {len(queries)} SIMBAD response(s) are 2xx",
              "SIMBAD returned an error:\n        " + "\n        ".join(errors))
    # Table content.
    tb = page.evaluate(JS_TABLE_STATE)
    if not tb.get("found"):
        rep.fail("no <table> found for the objects list (contract: <table id=\"objects-table\"> with <thead> and <tbody>)")
        return
    rows = tb.get("rows", [])
    n = len(rows)
    resp_rows = None
    for b in bodies:
        try:
            j = json.loads(b)
            if isinstance(j, dict) and isinstance(j.get("data"), list) and len(j["data"]) > 1:
                resp_rows = max(resp_rows or 0, len(j["data"]))
        except Exception:
            pass
    rep.check(n >= min_rows,
              f"table shows {n} rows (need >= {min_rows}); SIMBAD rows in response: {resp_rows}",
              f"table shows {n} rows (need >= {min_rows}; SIMBAD returned {resp_rows} rows in the response) - "
              f"check that the JSON 'data' array is rendered into <tbody>")
    rep.check(bool(tb.get("visible")), "objects table is visible", "objects table exists but is not visible (display:none / zero size)")
    # Anti-fixture: rendered identifiers must occur in the live response bytes.
    norm = lambda s: re.sub(r"\s+", " ", s)
    live = norm(" ".join(bodies))
    if live and rows:
        matched = 0
        for cells in rows:
            ids = [c for c in cells if len(c) >= 5 and re.search(r"[A-Za-z]", c)]
            if any(norm(c) in live or json.dumps(c)[1:-1] in live for c in ids):
                matched += 1
        rep.check(matched >= min(min_rows, n) and matched > 0,
                  f"{matched}/{n} rendered rows carry an identifier present in the live SIMBAD response",
                  f"only {matched}/{n} rendered rows carry an identifier found in the live SIMBAD response "
                  f"(need >= {min(min_rows, n)}) - the table is not rendered from the response (fixture data?)")
    # Row-count sentence. Its total must come from the census; the census check compares them.
    body_text = page.evaluate(JS_BODY_TEXT)
    m = re.search(r"showing\s+([\d,]+)\s+of\s+([\d,]+)", body_text, re.I)
    total_shown: int | None = None
    if not m:
        rep.fail("no row-count sentence like 'Showing 200 of 37,554 objects within 0.75°' in the visible text")
    else:
        shown, total_shown = int(m.group(1).replace(",", "")), int(m.group(2).replace(",", ""))
        rep.check(shown == n and total_shown >= shown,
                  f"row count sentence '{m.group(0)}' matches {n} rendered rows",
                  f"row count sentence '{m.group(0)}' disagrees with the table ({n} rows rendered; total must be >= shown)")
    headers = tb.get("headers", [])
    # Notability column: numeric and non-increasing on first load (server ORDER BY nbref DESC, sep_deg ASC).
    check_refs_column(headers, rows, rep)
    # Separation column: present, numeric, non-empty. Its order is asserted after the sort switch.
    check_sep_column(headers, rows, rep, require_ascending=False, context="on first load")
    # Field census: GROUP BY query, entries, and agreement with the row-count total.
    check_census(page, queries, rep, total_shown)


def check_refs_column(headers: list[str], rows: list[list[str]], rep: Report) -> None:
    idx, raw, vals = column_values(headers, rows, REFS_HEADER_RE)
    if idx is None:
        rep.fail(f"no table header matching /{REFS_HEADER_RE.pattern}/i (headers: {headers}) - "
                 f"contract: a 'Refs' column (SIMBAD nbref) sorted descending on first load")
        return
    name = headers[idx]
    bad = [raw[i] for i, v in enumerate(vals) if v is None]
    if bad:
        rep.fail(f"Refs column '{name}' has non-numeric cells: {bad[:5]} - render nbref as an integer "
                 f"(thousands separators are fine; nbref is never null)")
        return
    if not vals:
        rep.fail(f"Refs column '{name}' has no values (table body empty)")
        return
    i = next((k for k in range(1, len(vals)) if vals[k] > vals[k - 1] + 1e-9), None)
    if i is not None:
        rep.fail(f"Refs column '{name}' is not sorted descending on first load (row {i} has {raw[i - 1]}, "
                 f"row {i + 1} has {raw[i]}) - contract: the server orders by nbref DESC, sep_deg ASC and the "
                 f"client renders that order; sort only on select#sort change, and numerically")
    else:
        rep.ok(f"Refs column '{name}' non-increasing on first load ({raw[0]} .. {raw[-1]}, "
               f"{len(set(vals))} distinct values over {len(vals)} rows)")


def check_sep_column(headers: list[str], rows: list[list[str]], rep: Report, *,
                     require_ascending: bool, context: str) -> list[float] | None:
    idx, raw, vals = column_values(headers, rows, SEP_HEADER_RE)
    if idx is None:
        rep.fail(f"no table header matching /{SEP_HEADER_RE.pattern}/i {context} (headers: {headers}) - "
                 f"contract: a 'Sep (′)' column in arcminutes")
        return None
    name = headers[idx]
    bad = [raw[i] for i, v in enumerate(vals) if v is None]
    if bad:
        rep.fail(f"separation column '{name}' has non-numeric cells {context}: {bad[:5]}")
        return None
    if not vals:
        rep.fail(f"separation column '{name}' has no values {context} (table body empty)")
        return None
    if not require_ascending:
        rep.ok(f"separation column '{name}' numeric and non-empty {context} "
               f"({min(vals):.3f} .. {max(vals):.3f} over {len(vals)} rows)")
        return vals
    i = next((k for k in range(1, len(vals)) if vals[k] + 1e-9 < vals[k - 1]), None)
    if i is not None:
        rep.fail(f"separation column '{name}' is not sorted ascending {context} "
                 f"(row {i} has {raw[i - 1]}, row {i + 1} has {raw[i]})")
        return vals
    rep.ok(f"separation column '{name}' ascending {context} ({vals[0]:.3f} .. {vals[-1]:.3f})")
    return vals


def check_census(page, queries: list[tuple[dict, str]], rep: Report, total_shown: int | None) -> None:
    group_q = [q for _, q in queries if re.search(r"\bGROUP\s+BY\b", q, re.I)]
    rep.check(bool(group_q),
              f"census query sent ({len(group_q)} ADQL query(ies) with GROUP BY)",
              "no catalogue request contains GROUP BY - the field census must come from the census query in "
              "spec.md §5 (SELECT TOP 500 od.description AS otype_desc, COUNT(*) AS n ... GROUP BY od.description), "
              "not from the 200 rows and not from a COUNT(*) query")
    st = page.evaluate(JS_CENSUS_STATE)
    if not st.get("found"):
        rep.fail("no #field-census element - contract: a container above the table carrying data-total=\"<SUM(n)>\" "
                 "with one [data-count] child per object type (every group rendered, hidden beyond the top "
                 f"{CENSUS_INLINE}, '+ k more types' tail)")
        return
    entries = st.get("entries", [])
    counts = [cell_number(e["count"]) for e in entries]
    bad = [e["count"] for e, v in zip(entries, counts) if v is None or v < 1 or v != int(v)]
    visible = sum(1 for e in entries if e["visible"])
    rep.check(len(entries) >= MIN_CENSUS_ENTRIES and not bad,
              f"#field-census has {len(entries)} [data-count] entries with integer counts >= 1 ({visible} visible)",
              f"#field-census needs >= {MIN_CENSUS_ENTRIES} [data-count] entries with integer counts >= 1 "
              f"(found {len(entries)}; bad counts: {bad[:5]}) - one child per census group, data-count=\"<n>\"")
    rep.check(bool(st.get("visible")) and visible > 0,
              f"#field-census is visible: {st.get('text', '')[:120]}",
              f"#field-census exists but shows nothing (visible={st.get('visible')}, visible entries={visible})")
    if len(entries) > CENSUS_INLINE:
        more = re.search(r"\+\s*([\d,]+)\s+more", st.get("text", ""), re.I)
        k = int(more.group(1).replace(",", "")) if more else None
        rep.check(k is not None and k == len(entries) - visible,
                  f"census tail '+ {k} more types' matches {len(entries)} groups with {visible} shown",
                  f"#field-census has {len(entries)} groups but no honest '+ k more types' tail (expected k = "
                  f"{len(entries) - visible} = groups - visible entries; found {more.group(0) if more else 'none'}; "
                  f"show the top {CENSUS_INLINE} and hide the rest)")
    data_total = cell_number(st["total"]) if st.get("total") is not None else None
    sum_counts = int(sum(v for v in counts if v is not None))
    if data_total is None:
        rep.fail(f"#field-census has no numeric data-total attribute (got {st.get('total')!r}) - the gate reads the "
                 f"census total (SUM(n) over every group) from it")
    elif total_shown is not None:
        rep.check(int(data_total) == total_shown == sum_counts,
                  f"census total {int(data_total):,} = row-count total {total_shown:,} = sum of {len(entries)} entries",
                  f"census totals disagree: data-total={st.get('total')} row-count total={total_shown} sum of "
                  f"[data-count] entries={sum_counts} over {len(entries)} entries - render every group (hidden beyond "
                  f"the top {CENSUS_INLINE}) and use SUM(n) for both")


def check_sort_switch(page, net: NetLog, rep: Report) -> None:
    """Switch select#sort to 'sep': the loaded rows must re-order client-side, with no new request."""
    st = page.evaluate(JS_SORT_STATE)
    if not st.get("found"):
        rep.fail(f"no select#sort on the page (selects seen: {st.get('selects')}) - contract: <select id=\"sort\"> with "
                 f"options refs ('Most studied', selected on load) and sep ('Nearest to centre'); changing it re-sorts "
                 f"the loaded rows client-side")
        return
    options = st.get("options", [])
    values = [o["value"] for o in options]
    rep.check(sorted(values) == ["refs", "sep"] and st.get("value") == "refs",
              f"select#sort offers exactly refs/sep and is 'refs' on load (labels: {[o['text'] for o in options]})",
              f"select#sort must have exactly two options with values 'refs' (selected on load) and 'sep' "
              f"(found values {values}, selected {st.get('value')!r})")
    before = page.evaluate(JS_TABLE_STATE)
    rows_before = before.get("rows", [])
    ids_before = sorted(r[0] for r in rows_before if r)
    t0 = time.time()
    try:
        page.select_option(SORT_SELECT, "sep")
    except Exception as e:
        rep.fail(f"could not select 'sep' in select#sort: {str(e)[:200]}")
        return
    # Let the table settle: ascending separation, or no change for ~1 s, or 5 s at most.
    deadline, last, stable = t0 + 5.0, None, 0
    while True:
        tb = page.evaluate(JS_TABLE_STATE)
        _, _, vals = column_values(tb.get("headers", []), tb.get("rows", []), SEP_HEADER_RE)
        if vals and all(v is not None for v in vals) and all(vals[k] + 1e-9 >= vals[k - 1] for k in range(1, len(vals))):
            break
        snap = json.dumps(tb.get("rows", []))
        stable = stable + 1 if snap == last else 0
        last = snap
        if time.time() > deadline or stable >= 5:
            break
        page.wait_for_timeout(200)
    page.wait_for_timeout(400)  # a wrong implementation's network request gets a chance to show up
    tb = page.evaluate(JS_TABLE_STATE)
    headers, rows = tb.get("headers", []), tb.get("rows", [])
    check_sep_column(headers, rows, rep, require_ascending=True, context="after selecting 'Nearest to centre' (sep)")
    ids_after = sorted(r[0] for r in rows if r)
    rep.check(ids_after == ids_before and len(rows) == len(rows_before),
              f"the same {len(rows)} rows were re-ordered client-side",
              f"row set changed after the sort switch ({len(rows_before)} -> {len(rows)} rows, "
              f"{len(set(ids_before) ^ set(ids_after))} identifiers differ) - re-order the loaded rows; do not re-query")
    new_reqs = net.of_kind("catalogue", t0)
    rep.check(not new_reqs,
              "sort switch made no catalogue request",
              f"sort switch sent {len(new_reqs)} request(s) to {CATALOGUE_HOST} (e.g. {new_reqs[0]['url'][:140] if new_reqs else ''}) - "
              f"sorting must happen client-side on the loaded rows")


