def wait_for_outcome(page, net: NetLog, min_rows: int, timeout: float, clicked_at: float) -> str:
    """Poll until the happy-path criteria are met, the page goes quiet, or the deadline passes."""
    deadline = clicked_at + timeout
    while True:
        img_ok = cat_ok = rows_ok = False
        for r in net.of_kind("image", clicked_at):
            if r["status"] == 200 and (r["ctype"] or "").startswith("image/"):
                img_ok = True
        for r in net.of_kind("catalogue", clicked_at):
            if r["status"] is not None and 200 <= r["status"] < 300:
                cat_ok = True
        if img_ok:
            st = page.evaluate(JS_IMAGE_STATE)
            img_ok = bool(st.get("found") and st.get("complete") and st.get("naturalWidth", 0) >= MIN_NATURAL_WIDTH)
        if cat_ok:
            tb = page.evaluate(JS_TABLE_STATE)
            rows_ok = bool(tb.get("found") and len(tb.get("rows", [])) >= min_rows)
            body = page.evaluate(JS_BODY_TEXT)
            rows_ok = rows_ok and bool(re.search(r"showing\s+[\d,]+\s+of\s+[\d,]+", body, re.I))
        if img_ok and cat_ok and rows_ok:
            return "ready"
        now = time.time()
        if now > deadline:
            return "timeout"
        if now - clicked_at > 6 and net.pending == 0 and now - net.last_activity > 3:
            return "quiet"
        page.wait_for_timeout(250)


def check_image(page, net: NetLog, rep: Report, since: float) -> None:
    reqs = net.of_kind("image", since)
    if not rep.check(bool(reqs),
                     f"{len(reqs)} request(s) to hips2fits host(s) {IMAGE_HOSTS}",
                     f"0 requests to a hips2fits host {IMAGE_HOSTS} after clicking Explore - "
                     f"the image panel is not fetching a real cutout"):
        return
    good: dict | None = None
    problems: list[str] = []
    for r in reqs:
        p = request_params(r)
        issues = []
        ra, dec = to_float(p.get("ra")), to_float(p.get("dec"))
        if ra is None or dec is None:
            issues.append(f"ra/dec missing from query (ra={p.get('ra')!r}, dec={p.get('dec')!r})")
        else:
            if ang_sep_deg(ra, dec, PRESET["ra"], PRESET["dec"]) > COORD_TOL_DEG:
                swapped = (abs(ra - PRESET["dec"]) < COORD_TOL_DEG and abs(dec - PRESET["ra"]) < COORD_TOL_DEG)
                issues.append(
                    f"ra={ra}, dec={dec} but {PRESET['label']} is ra={PRESET['ra']}, dec={PRESET['dec']} "
                    f"(tolerance {COORD_TOL_DEG} deg)" + (" - RA AND DEC ARE SWAPPED" if swapped else " - wrong place"))
        fmt = (p.get("format") or "").lower()
        if fmt not in ("jpg", "jpeg", "png"):
            issues.append(f"format={p.get('format')!r} - must be jpg or png (service default is FITS, which <img> cannot render)")
        hips = p.get("hips") or ""
        if "/" not in hips:
            issues.append(f"hips={hips!r} - must be a full HiPS ID such as CDS/P/DSS2/color, never a keyword")
        fov = to_float(p.get("fov"))
        if fov is None or not (FOV_RANGE_DEG[0] <= fov <= FOV_RANGE_DEG[1]):
            issues.append(f"fov={p.get('fov')!r} - must be decimal DEGREES in [{FOV_RANGE_DEG[0]}, {FOV_RANGE_DEG[1]}] (arcminutes?)")
        w, h = to_float(p.get("width")), to_float(p.get("height"))
        if w is None or h is None or w < MIN_NATURAL_WIDTH or h < MIN_NATURAL_WIDTH:
            issues.append(f"width={p.get('width')!r} height={p.get('height')!r} - both required, >= {MIN_NATURAL_WIDTH} px")
        if r["failed"]:
            issues.append(f"request failed at network level: {r['failed']}")
        elif r["status"] != 200 or not (r["ctype"] or "").startswith("image/"):
            issues.append(f"response was HTTP {r['status']} content-type={r['ctype']!r} (need 200 image/*)")
        if not issues:
            good = r
        else:
            problems.append(f"{r['method']} {r['url'][:160]}... -> " + "; ".join(issues))
    if good is None:
        rep.fail("no hips2fits request satisfied the contract:\n        " + "\n        ".join(problems))
    else:
        p = request_params(good)
        rep.ok(f"hips2fits request OK: hips={p.get('hips')} ra={p.get('ra')} dec={p.get('dec')} fov={p.get('fov')} "
               f"{p.get('width')}x{p.get('height')} format={p.get('format')} -> HTTP {good['status']} {good['ctype']}")
    st = page.evaluate(JS_IMAGE_STATE)
    if not st.get("found"):
        rep.fail(f"no <img> showing the cutout found ({st.get('imgCount', 0)} <img> elements on page; "
                 f"contract: <img id=\"sky-image\">)")
        return
    src = st.get("src") or ""
    src_ok = True
    if re.match(r"^(blob|data):", src, re.I):
        src_desc = f"{src[:30]}... (fetched by script)"
    elif classify(src) == "image":
        p = request_params({"url": src, "post": None})
        ra, dec = to_float(p.get("ra")), to_float(p.get("dec"))
        src_ok = ra is not None and dec is not None and ang_sep_deg(ra, dec, PRESET["ra"], PRESET["dec"]) <= COORD_TOL_DEG
        src_desc = f"hips2fits ra={p.get('ra')} dec={p.get('dec')}"
    else:
        src_ok = False
        src_desc = src[:120] or "(empty)"
    rep.check(src_ok, f"<img{'#' + st['id'] if st.get('id') else ''}> src is the live cutout: {src_desc}",
              f"<img{'#' + st['id'] if st.get('id') else ''}> src is not the M31 cutout from hips2fits: {src_desc}")
    rep.check(bool(st.get("complete")) and st.get("naturalWidth", 0) >= MIN_NATURAL_WIDTH,
              f"image decoded: naturalWidth={st.get('naturalWidth')} naturalHeight={st.get('naturalHeight')}",
              f"image not decoded: complete={st.get('complete')} naturalWidth={st.get('naturalWidth')} "
              f"(need >= {MIN_NATURAL_WIDTH}) - broken <img>, wrong bytes (FITS?), or onerror swallowed")
    rep.check(bool(st.get("visible")) and st.get("width", 0) >= MIN_RENDERED_WIDTH,
              f"image visible on screen: {st.get('width'):.0f}x{st.get('height'):.0f} css px",
              f"image not visible or too small on screen: visible={st.get('visible')} width={st.get('width')} "
              f"(need >= {MIN_RENDERED_WIDTH} css px)")


