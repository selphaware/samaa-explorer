def preflight_network() -> None:
    # Always the real services, even under --selftest-inject: the injection must exercise the mid-run path.
    for name, url in PREFLIGHT_URLS:
        p = http_probe(url, None, 25)
        if p["status"] is None:
            raise HarnessError(
                f"{name} is unreachable from this machine ({p['detail']} after {p['seconds']:.1f}s). "
                f"Network / DNS / proxy problem or service outage - not a deliverable problem; retry in a minute.")
        if p["status"] != 200:
            raise HarnessError(f"{name} answered HTTP {p['status']} to the gate's known-good request after "
                               f"{p['seconds']:.1f}s - service outage, not a deliverable problem; retry in a minute.")


