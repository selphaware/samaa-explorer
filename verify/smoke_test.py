# Upstream failure during the run: service outage (exit 3) or the page's own request (exit 1)?
# --------------------------------------------------------------------------------------
def http_probe(url: str, post: str | None, timeout: float) -> dict:
    """One request sent by the gate itself. {status, detail, seconds, acao, body}; status None = no HTTP answer."""
    t0 = time.time()
    data = post.encode("utf-8") if post else None
    headers = {"User-Agent": UA}
    if data is not None:
        headers["Content-Type"] = "application/x-www-form-urlencoded"
    try:
        with urllib.request.urlopen(urllib.request.Request(url, data=data, headers=headers), timeout=timeout) as r:
            body = r.read(4096)
            return {"status": r.status, "detail": f"HTTP {r.status}", "seconds": time.time() - t0,
                    "acao": r.headers.get("Access-Control-Allow-Origin"), "body": body.decode("utf-8", "replace")}
    except urllib.error.HTTPError as e:
        body = ""
        try:
            body = e.read(4096).decode("utf-8", "replace")
        except Exception:
            pass
        return {"status": e.code, "detail": f"HTTP {e.code}", "seconds": time.time() - t0,
                "acao": e.headers.get("Access-Control-Allow-Origin") if e.headers else None, "body": body}
    except Exception as e:
        reason = getattr(e, "reason", None)
        txt = str(reason if reason is not None else e)
        low = txt.lower()
        if "refused" in low or isinstance(reason, ConnectionRefusedError):
            detail = "connection refused"
        elif "timed out" in low or isinstance(e, TimeoutError) or isinstance(reason, TimeoutError):
            detail = "timed out"
        elif "reset" in low or isinstance(reason, ConnectionResetError):
            detail = "connection reset"
        elif "getaddrinfo" in low or "name or service not known" in low or "nodename" in low:
            detail = "DNS resolution failed"
        else:
            detail = f"{e.__class__.__name__}: {txt[:120]}"
        return {"status": None, "detail": detail, "seconds": time.time() - t0, "acao": None, "body": ""}


