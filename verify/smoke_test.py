class _QuietHandler(SimpleHTTPRequestHandler):
    # Windows' registry can map .js to text/plain, which breaks <script type="module">.
    # Pin the types the page needs so a harness quirk is never blamed on the code.
    extensions_map = {
        **SimpleHTTPRequestHandler.extensions_map,
        ".html": "text/html; charset=utf-8",
        ".htm": "text/html; charset=utf-8",
        ".js": "text/javascript; charset=utf-8",
        ".mjs": "text/javascript; charset=utf-8",
        ".css": "text/css; charset=utf-8",
        ".json": "application/json",
        ".svg": "image/svg+xml",
        ".png": "image/png",
        ".jpg": "image/jpeg",
        ".jpeg": "image/jpeg",
        ".gif": "image/gif",
        ".webp": "image/webp",
        ".ico": "image/x-icon",
        ".woff": "font/woff",
        ".woff2": "font/woff2",
        ".txt": "text/plain; charset=utf-8",
    }

    gate_nonce = ""  # set per run; lets the gate prove the page came from THIS server

    def log_message(self, *args) -> None:  # silence per-request logging
        pass

    def end_headers(self) -> None:
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Samaa-Gate", self.gate_nonce)
        super().end_headers()


class _Server(ThreadingHTTPServer):
    # http.server.HTTPServer sets allow_reuse_address = 1. On Windows that lets a second gate
    # bind an already-used port and silently receive the OTHER process's pages. Refuse instead
    # and fall back to a free port.
    allow_reuse_address = False
    allow_reuse_port = False
    daemon_threads = True


def start_server(root: Path, port: int, rep: Report, nonce: str):
    handler_cls = type("GateHandler", (_QuietHandler,), {"gate_nonce": nonce})
    handler = partial(handler_cls, directory=str(root))
    try:
        srv = _Server(("127.0.0.1", port), handler)
    except OSError as e:
        try:
            srv = _Server(("127.0.0.1", 0), handler)
        except OSError as e2:
            raise HarnessError(f"cannot bind a local port for the static server ({e}; fallback: {e2})")
        rep.info(f"port {port} busy ({e.strerror}); serving on {srv.server_address[1]} instead")
    t = threading.Thread(target=srv.serve_forever, kwargs={"poll_interval": 0.2}, daemon=True)
    t.start()
    return srv, srv.server_address[1]


