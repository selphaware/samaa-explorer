def check_catalogue(page, net: NetLog, rep: Report, since: float, min_rows: int) -> None:
    reqs = net.of_kind("catalogue", since)
    if not rep.check(bool(reqs),
                     f"{len(reqs)} request(s) to {CATALOGUE_HOST}",
                     f"0 requests to {CATALOGUE_HOST} after clicking Explore - table is not backed by a live "
                     f"SIMBAD query (fixture data?)"):
        return
    queries: list[tuple[dict, str]] = []
    for r in reqs:
        p = request_params(r)
        q = p.get("query") or ""
        if not q:
            rep.fail(f"catalogue request has no ADQL QUERY parameter: {r['method']} {r['url'][:160]} - "
                     f"TAP sync expects REQUEST=doQuery&LANG=ADQL&FORMAT=json&QUERY=<ADQL>")
            continue
        queries.append((r, q))
    if not queries:
        return
    # Every ADQL query the page sends must carry TOP n, n <= MAX_TOP.
    bad_top = []
    for r, q in queries:
        m = TOP_RE.search(q)
        if not m:
            bad_top.append(f"no TOP cap: {q[:140]}")
        elif not (1 <= int(m.group(1)) <= MAX_TOP):
            bad_top.append(f"TOP {m.group(1)} exceeds {MAX_TOP}: {q[:140]}")
    rep.check(not bad_top, f"all {len(queries)} ADQL query(ies) carry TOP n with n <= {MAX_TOP}",
              "ADQL without a valid TOP cap:\n        " + "\n        ".join(bad_top))
    # At least one cone centred on the preset.
    cone_hits = []
    cone_misses = []
    for r, q in queries:
        m = CIRCLE_RE.search(q)
        if not m:
            cone_misses.append(f"no CIRCLE( in: {q[:140]}")
            continue
        ra, dec, rad = float(m.group(1)), float(m.group(2)), float(m.group(3))
        sep = ang_sep_deg(ra, dec, PRESET["ra"], PRESET["dec"])
        if sep > COORD_TOL_DEG:
            swapped = (abs(ra - PRESET["dec"]) < COORD_TOL_DEG and abs(dec - PRESET["ra"]) < COORD_TOL_DEG)
            cone_misses.append(f"CIRCLE centre ({ra}, {dec}) is {sep:.3f} deg from {PRESET['label']}"
                               + (" - RA AND DEC ARE SWAPPED" if swapped else ""))
        elif not (RADIUS_RANGE_DEG[0] <= rad <= RADIUS_RANGE_DEG[1]):
            cone_misses.append(f"CIRCLE radius {rad} deg outside {RADIUS_RANGE_DEG} (arcminutes? FoV instead of FoV/2?)")
        else:
            cone_hits.append((r, q, rad))
    rep.check(bool(cone_hits),
              f"ADQL cone centred on {PRESET['label']} within {COORD_TOL_DEG} deg, radius {cone_hits[0][2] if cone_hits else '?'} deg",
              "no ADQL query contains CIRCLE( centred on the selected preset:\n        " + "\n        ".join(cone_misses))
    # Responses must be non-error.
    errors = []
    bodies = []
    for r, q in queries:
        if r["failed"]:
            errors.append(f"network failure ({r['failed']}): {q[:100]}")
        elif r["status"] is None:
            errors.append(f"no response received: {q[:100]}")
        elif not (200 <= r["status"] < 300):
            body = catalogue_body_text(r)
            msg = re.search(r'QUERY_STATUS"\s+value="ERROR">([^<]*)<', body)
            errors.append(f"HTTP {r['status']} {r['ctype']}: {msg.group(1).strip() if msg else body[:160]!r} for {q[:100]}")
        else:
            bodies.append(catalogue_body_text(r))
    rep.check(not errors, f"all {len(queries)} SIMBAD response(s) are 2xx",
              "SIMBAD returned an error:\n        " + "\n        ".join(errors))
    # Table content.
    tb = page.evaluate(JS_TABLE_STATE)
    if not tb.get("found"):
        rep.fail("no <table> found for the objects list (contract: <table id=\"objects-table\"> with <thead> and <tbody>)")
        return
    rows = tb.get("rows", [])
    n = len(rows)
    resp_rows = None
    for b in bodies:
        try:
            j = json.loads(b)
            if isinstance(j, dict) and isinstance(j.get("data"), list) and len(j["data"]) > 1:
                resp_rows = max(resp_rows or 0, len(j["data"]))
        except Exception:
            pass
    rep.check(n >= min_rows,
              f"table shows {n} rows (need >= {min_rows}); SIMBAD rows in response: {resp_rows}",
              f"table shows {n} rows (need >= {min_rows}; SIMBAD returned {resp_rows} rows in the response) - "
              f"check that the JSON 'data' array is rendered into <tbody>")
    rep.check(bool(tb.get("visible")), "objects table is visible", "objects table exists but is not visible (display:none / zero size)")
    # Anti-fixture: rendered identifiers must occur in the live response bytes.
    norm = lambda s: re.sub(r"\s+", " ", s)
    live = norm(" ".join(bodies))
    if live and rows:
        matched = 0
        for cells in rows:
            ids = [c for c in cells if len(c) >= 5 and re.search(r"[A-Za-z]", c)]
            if any(norm(c) in live or json.dumps(c)[1:-1] in live for c in ids):
                matched += 1
        rep.check(matched >= min(min_rows, n) and matched > 0,
                  f"{matched}/{n} rendered rows carry an identifier present in the live SIMBAD response",
                  f"only {matched}/{n} rendered rows carry an identifier found in the live SIMBAD response "
                  f"(need >= {min(min_rows, n)}) - the table is not rendered from the response (fixture data?)")
    # Row-count sentence.
    body_text = page.evaluate(JS_BODY_TEXT)
    m = re.search(r"showing\s+([\d,]+)\s+of\s+([\d,]+)", body_text, re.I)
    if not m:
        rep.fail("no row-count sentence like 'Showing 200 of 37553 objects within 0.75°' in the visible text")
    else:
        shown, total = int(m.group(1).replace(",", "")), int(m.group(2).replace(",", ""))
        rep.check(shown == n and total >= shown,
                  f"row count sentence '{m.group(0)}' matches {n} rendered rows",
                  f"row count sentence '{m.group(0)}' disagrees with the table ({n} rows rendered; total must be >= shown)")
    # Separation column, ascending.
    headers = tb.get("headers", [])
    sep_idx = next((i for i, h in enumerate(headers) if re.search(r"sep|separation|dist", h, re.I)), None)
    if sep_idx is None:
        rep.fail(f"no table header matching /sep|separation|dist/i (headers: {headers}) - "
                 f"contract: a 'Sep (arcmin)' column sorted ascending")
    else:
        vals = [to_float(re.sub(r"[^\d.+-eE]", "", c[sep_idx])) if sep_idx < len(c) else None for c in rows]
        if any(v is None for v in vals):
            rep.fail(f"separation column '{headers[sep_idx]}' has non-numeric cells: "
                     f"{[c[sep_idx] for c in rows if sep_idx < len(c)][:5]}")
        else:
            unsorted = [i for i in range(1, len(vals)) if vals[i] + 1e-9 < vals[i - 1]]
            if not vals:
                rep.fail(f"separation column '{headers[sep_idx]}' has no values (table body empty)")
            elif unsorted:
                i = unsorted[0]
                rep.fail(f"separation column '{headers[sep_idx]}' is not sorted ascending "
                         f"(row {i}: {vals[i - 1]} then {vals[i]})")
            else:
                rep.ok(f"separation column '{headers[sep_idx]}' ascending ({vals[0]:.3f} .. {vals[-1]:.3f})")


